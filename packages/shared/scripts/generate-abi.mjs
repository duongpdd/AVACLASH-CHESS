import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const contractsOutDir = path.resolve(__dirname, "../../../contracts/out");

const artifactPath = path.resolve(
  __dirname,
  "../../../contracts/out/ChessEscrow.sol/ChessEscrow.json"
);

const metaArtifactPath = path.resolve(
  __dirname,
  "../../../contracts/out/AvaClashMeta.sol/AvaClashMeta.json"
);

const outDir = path.resolve(__dirname, "../src/abi");

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

// If contracts/out directory does not exist, warn and gracefully skip without error
if (!fs.existsSync(contractsOutDir)) {
  console.warn(
    `[generate-abi] Cảnh báo: contracts/out không tồn tại (${contractsOutDir}). Bỏ qua sinh ABI và sử dụng tệp ABI đã commit.`
  );
  process.exit(0);
}

if (!fs.existsSync(artifactPath)) {
  console.warn(
    `[generate-abi] Cảnh báo: Artifact không tồn tại tại ${artifactPath}. Bỏ qua sinh ABI và sử dụng tệp ABI đã commit.`
  );
  process.exit(0);
}

const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf-8"));
const abiTs = `// Autogenerated from contracts/out/ChessEscrow.sol/ChessEscrow.json
// DO NOT EDIT MANUALLY - run 'pnpm generate-abi' in @avaclash/shared
export const CHESS_ESCROW_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
export default CHESS_ESCROW_ABI;
`;

const targetFile = path.join(outDir, "ChessEscrow.ts");
fs.writeFileSync(targetFile, abiTs, "utf-8");
console.log(`[generate-abi] Successfully generated ${targetFile}`);

if (fs.existsSync(metaArtifactPath)) {
  const metaArtifact = JSON.parse(fs.readFileSync(metaArtifactPath, "utf-8"));
  const metaAbiTs = `// Autogenerated from contracts/out/AvaClashMeta.sol/AvaClashMeta.json
// DO NOT EDIT MANUALLY - run 'pnpm generate-abi' in @avaclash/shared
export const AVA_CLASH_META_ABI = ${JSON.stringify(metaArtifact.abi, null, 2)} as const;
export default AVA_CLASH_META_ABI;
`;
  const metaTargetFile = path.join(outDir, "AvaClashMeta.ts");
  fs.writeFileSync(metaTargetFile, metaAbiTs, "utf-8");
  console.log(`[generate-abi] Successfully generated ${metaTargetFile}`);
}

for (const [name, exportName] of [
  ["AvaClashCosmetics", "COSMETICS_ABI"],
  ["CosmeticAuction", "COSMETIC_AUCTION_ABI"],
]) {
  const artifact = path.join(contractsOutDir, `${name}.sol/${name}.json`);
  if (!fs.existsSync(artifact)) continue;
  const { abi } = JSON.parse(fs.readFileSync(artifact, "utf-8"));
  fs.writeFileSync(
    path.join(outDir, `${name}.ts`),
    `// Autogenerated from ${name}.sol; run pnpm generate-abi.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    "utf-8",
  );
}

const indexTs = `// Autogenerated exports for ABIs
export { CHESS_ESCROW_ABI } from "./ChessEscrow.js";
export { AVA_CLASH_META_ABI } from "./AvaClashMeta.js";
`;
fs.writeFileSync(path.join(outDir, "index.ts"), indexTs, "utf-8");
